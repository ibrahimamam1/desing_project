def fig_cross():
    fig, ax = plt.subplots(figsize=(8, 4.2))
    ax.barh([k for k, _, _ in cross], [v for _, v, _ in cross],
            color=[GREY if s.startswith("Pre") else GREEN for *_, s in cross])
    for y, (_, v, _) in enumerate(cross):
        ax.text(v + 0.08, y, f"{v:.2f}%", va="center", fontsize=9)
    ax.set_xlim(0, max(v for _, v, _ in cross) * 1.13)
    ax.invert_yaxis()
    ax.set_xlabel("Mean collision rate (%)")
    ax.set_title("Collision rate on the pre-defence benchmark")
    ax.legend(handles=[Patch(color=GREY, label="Pre-defence study (reported)"),
                       Patch(color=GREEN, label=src_label)], loc="lower right", fontsize=8)
    plt.tight_layout()
    plt.savefig(os.path.join(FIG, "cross_study_collision.png"), dpi=200)
    plt.close(fig)


def fig_ci(got, name, title):
    if not got:
        return
    items = sorted(got.items(), key=lambda kv: -kv[1]["col"])
    fig, ax = plt.subplots(figsize=(8, 0.55 * len(items) + 1.4))
    for y, (k, s) in enumerate(items):
        lo, hi = wilson(s["c"], s["n"])
        col = GREEN if "Shield" in k else (GREY if "Heuristic" in k else BLUE)
        ax.plot([lo, hi], [y, y], color=col, lw=2.5)
        ax.plot(s["col"], y, "o", color=col)
        ax.text(hi + 0.08, y, f"{s['col']:.2f}%", va="center", fontsize=8)
    ax.set_yticks(range(len(items)))
    ax.set_yticklabels([k for k, _ in items], fontsize=8)
    ax.invert_yaxis()
    ax.set_xlabel("Collision rate (%) with 95% confidence interval")
    ax.set_title(title)
    plt.tight_layout()
    plt.savefig(os.path.join(FIG, name), dpi=200)
    plt.close(fig)


