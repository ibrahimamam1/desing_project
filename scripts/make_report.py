# ------------------------------------------------------------------ stats
def fisher(a, b, n1, n2):
    """Two-sided Fisher exact test on a collisions vs b collisions."""
    A, B, C, D = a, n1 - a, b, n2 - b
    N = A + B + C + D
    p = lambda x: comb(A + B, x) * comb(C + D, A + C - x) / comb(N, A + C)
    lo, hi = max(0, A + C - (C + D)), min(A + B, A + C)
    p0 = p(A)
    return min(sum(p(x) for x in range(lo, hi + 1) if p(x) <= p0 + 1e-12), 1.0)


def wilson(c, n, z=1.96):
    if n == 0:
        return 0.0, 0.0
    ph = c / n
    d = 1 + z * z / n
    ctr = (ph + z * z / (2 * n)) / d
    hw = z * math.sqrt(ph * (1 - ph) / n + z * z / (4 * n * n)) / d
    return 100 * max(0.0, ctr - hw), 100 * (ctr + hw)


def load(tag):
    """Summary of one result file, or None if it does not exist or is incomplete."""
    f = os.path.join(RES, f"{tag}_results.csv")
    if not os.path.exists(f):
        return None
    rows = list(csv.DictReader(open(f)))
    if not rows:
        return None
    n = sum(int(r["n_episodes"]) for r in rows)
    c = sum(int(r["collisions"]) for r in rows)
    k = len(rows)
    by = {}
    for r in rows:
        by.setdefault(r["scenario"], []).append(float(r["collision_rate"]))
    return dict(
        rows=k, c=c, n=n, col=100 * c / n,
        succ=sum(float(r["success_rate"]) for r in rows) / k,
        tt=sum(float(r["avg_travel_time"]) for r in rows) / k,
        wait=sum(float(r.get("avg_waiting_time") or 0) for r in rows) / k,
        ovr=100 * sum(float(r.get("shield_override_rate") or 0) for r in rows) / k,
        by_sc={s: statistics.mean(v) for s, v in by.items()},
    )


